SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_LENGTH, CHAR_LENGTH, CHAR_USED,
       DATA_PRECISION, DATA_SCALE, NULLABLE, DATA_DEFAULT
FROM USER_TAB_COLUMNS WHERE TABLE_NAME IN ('CUSTOMER','PRODUCT','STOCK','TRADE')
ORDER BY TABLE_NAME,COLUMN_ID;
SELECT C.TABLE_NAME, C.CONSTRAINT_NAME, C.CONSTRAINT_TYPE, CC.COLUMN_NAME, CC.POSITION, C.R_CONSTRAINT_NAME
FROM USER_CONSTRAINTS C JOIN USER_CONS_COLUMNS CC ON C.CONSTRAINT_NAME=CC.CONSTRAINT_NAME
WHERE C.TABLE_NAME IN ('CUSTOMER','PRODUCT','STOCK','TRADE')
ORDER BY C.TABLE_NAME,C.CONSTRAINT_NAME,CC.POSITION;
SELECT SEQUENCE_NAME, INCREMENT_BY, LAST_NUMBER FROM USER_SEQUENCES ORDER BY SEQUENCE_NAME;
SELECT TABLE_NAME, TRIGGER_NAME, TRIGGER_BODY FROM USER_TRIGGERS
WHERE TABLE_NAME IN ('CUSTOMER','PRODUCT','STOCK','TRADE');
